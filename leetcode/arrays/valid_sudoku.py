def is_valid_sudoku(board: list[list[str]]) -> bool:
    filas: dict[int, set] = {i: set() for i in range(9)}
    columnas: dict[int, set] = {i: set() for i in range(9)}
    cajas: dict[tuple, set] = {(r, c): set() for r in range(3) for c in range(3)}

    for i in range(9):
        for j in range(9):
            num = board[i][j]
            if not num.isdigit():
                continue
            if num in filas[i] or num in columnas[j] or num in cajas[(i//3,j//3)]:
                return False
            filas[i].add(num)
            columnas[j].add(num)
            cajas[(i//3,j//3)].add(num)

    return True

